CREATE TABLE IF NOT EXISTS attendance_certifications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    employment_id BIGINT UNSIGNED NOT NULL,
    starts_on DATE NOT NULL,
    ends_before DATE NOT NULL,
    watermark BIGINT UNSIGNED NOT NULL,
    shift_watermark BIGINT UNSIGNED NOT NULL,
    expected_shifts SMALLINT UNSIGNED NOT NULL,
    worked_minutes INT UNSIGNED NOT NULL,
    absent_minutes INT UNSIGNED NOT NULL,
    evidence JSON NOT NULL,
    decision_ref VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    notes VARCHAR(600) NOT NULL,
    certified_by BIGINT UNSIGNED NOT NULL,
    certified_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uq_attendance_certification_input (group_id, company_id, employment_id, starts_on, ends_before, shift_watermark),
    UNIQUE KEY uq_attendance_certification_decision (group_id, company_id, decision_ref),
    UNIQUE KEY uq_attendance_certification_scope (group_id, company_id, employment_id, id),
    KEY ix_attendance_certification_cut (group_id, company_id, employment_id, starts_on, ends_before, watermark, id),
    FOREIGN KEY (group_id, company_id, employment_id) REFERENCES employments (group_id, company_id, id),
    FOREIGN KEY (group_id, certified_by) REFERENCES accounts (group_id, id),
    CHECK (ends_before>starts_on),
    CHECK (shift_watermark<=watermark),
    CHECK (expected_shifts<=1000)
) ENGINE=InnoDB;
