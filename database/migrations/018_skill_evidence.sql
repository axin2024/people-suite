CREATE TABLE IF NOT EXISTS skill_evidence (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    employment_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    skill VARCHAR(48) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    title VARCHAR(160) NOT NULL,
    evidence_ref VARCHAR(400) NOT NULL,
    reviewer_id BIGINT UNSIGNED NOT NULL,
    visibility ENUM('private','company','group') NOT NULL DEFAULT 'private',
    state ENUM('submitted','verified','rejected') NOT NULL DEFAULT 'submitted',
    verified_from DATE NULL,
    verified_until DATE NULL,
    review_notes VARCHAR(400) NULL,
    revision INT UNSIGNED NOT NULL DEFAULT 1,
    UNIQUE KEY uq_skill_evidence_scope (group_id,company_id,id),
    KEY ix_employee_skills (group_id,employee_id,skill,state,verified_until),
    KEY ix_skill_directory (group_id,skill,state,visibility,id),
    FOREIGN KEY (group_id,company_id,employment_id) REFERENCES employments (group_id,company_id,id),
    FOREIGN KEY (group_id,employee_id) REFERENCES employees (group_id,id),
    FOREIGN KEY (group_id,reviewer_id) REFERENCES accounts (group_id,id),
    CHECK (state<>'verified' OR (verified_from IS NOT NULL AND verified_until>=verified_from))
) ENGINE=InnoDB;
