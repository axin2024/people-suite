CREATE TABLE IF NOT EXISTS employee_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    employment_id BIGINT UNSIGNED NOT NULL,
    employee_account_id BIGINT UNSIGNED NOT NULL,
    reference VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    details VARCHAR(1600) NOT NULL,
    requested_name VARCHAR(160) NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
    version TINYINT UNSIGNED NOT NULL DEFAULT 1,
    submitted_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    decided_by BIGINT UNSIGNED NULL,
    decision_ref VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL,
    response VARCHAR(1600) NULL,
    outcome JSON NULL,
    decided_at DATETIME(6) NULL,
    UNIQUE KEY uq_employee_request_reference (group_id, company_id, employment_id, reference),
    KEY ix_employee_requests_self (group_id, company_id, employee_account_id, id),
    KEY ix_employee_requests_review (group_id, company_id, state, id),
    KEY ix_employee_requests_employment (group_id, company_id, employment_id, state, id),
    FOREIGN KEY (group_id, company_id, employment_id) REFERENCES employments (group_id, company_id, id),
    FOREIGN KEY (group_id, employee_account_id) REFERENCES accounts (group_id, id),
    FOREIGN KEY (group_id, decided_by) REFERENCES accounts (group_id, id),
    CHECK (kind IN ('employment_certificate','name_correction','other')),
    CHECK ((kind='name_correction')=(requested_name IS NOT NULL)),
    CHECK ((state='pending' AND version=1 AND decided_by IS NULL AND decided_at IS NULL AND decision_ref IS NULL AND response IS NULL AND outcome IS NULL)
        OR (state IN ('approved','rejected','withdrawn') AND version=2 AND decided_by IS NOT NULL AND decided_at IS NOT NULL
            AND decision_ref IS NOT NULL AND response IS NOT NULL)),
    CHECK ((state='approved')=(outcome IS NOT NULL)),
    CHECK (state NOT IN ('approved','rejected') OR decided_by<>employee_account_id),
    CHECK (state<>'withdrawn' OR decided_by=employee_account_id)
) ENGINE=InnoDB;
