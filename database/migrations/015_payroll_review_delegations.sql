CREATE TABLE IF NOT EXISTS payroll_review_delegations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    run_id BIGINT UNSIGNED NOT NULL,
    run_version INT UNSIGNED NOT NULL,
    trial_id BIGINT UNSIGNED NOT NULL,
    granted_by BIGINT UNSIGNED NOT NULL,
    delegate_id BIGINT UNSIGNED NOT NULL,
    notes VARCHAR(600) NOT NULL,
    state VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'assigned',
    assigned_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at DATETIME(6) NOT NULL,
    finished_at DATETIME(6) NULL,
    assigned_version INT UNSIGNED AS (CASE WHEN state='assigned' THEN run_version END) STORED,
    resulting_version INT UNSIGNED AS (CASE WHEN state='used' THEN run_version+1 END) STORED,
    UNIQUE KEY uq_payroll_delegation_current (group_id, company_id, run_id, assigned_version),
    UNIQUE KEY uq_payroll_delegation_result (group_id, company_id, run_id, resulting_version),
    FOREIGN KEY (group_id, company_id, run_id) REFERENCES payroll_runs (group_id, company_id, id),
    FOREIGN KEY (group_id, company_id, trial_id) REFERENCES payroll_trials (group_id, company_id, id),
    FOREIGN KEY (group_id, granted_by) REFERENCES accounts (group_id, id),
    FOREIGN KEY (group_id, delegate_id) REFERENCES accounts (group_id, id),
    CHECK (delegate_id<>granted_by),
    CHECK (state IN ('assigned','revoked','superseded','used'))
) ENGINE=InnoDB;
